package com.AgricultureFMSystem.AgricultureFMSystem.enums;

/**
 * Categorization of agriculture farm expenses.
 */
public enum ExpenseCategory {
    SEEDS,          // Certified seeds or nursery seedlings
    FERTILIZERS,    // NPK, compost, micronutrients
    PESTICIDES,     // Fungicides, herbicides, insecticides
    LABOR,          // Daily wages or contracted field workers
    MACHINERY,      // Tractor rental, harvesters, repair
    FUEL,           // Diesel / petrol for pumps, generators, tractors
    IRRIGATION,     // Electricity bills, canal tax, water pipes
    PACKAGING,      // Bags, boxes, crates
    TRANSPORT,      // Transport to market or cold storage
    MISCELLANEOUS   // Administrative, licenses, other farm tools
}
