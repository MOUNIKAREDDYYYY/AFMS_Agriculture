package com.AgricultureFMSystem.AgricultureFMSystem.entity.enums;

/**
 * Types of farming activities carried out on a field.
 */
public enum ActivityType {
    SOIL_PREPARATION, // Plowing, harrowing, leveling
    PLANTING,          // Seed sowing or transplanting
    IRRIGATION,        // Watering crops via drip, sprinkler, etc.
    FERTILIZING,       // Applying chemical or organic fertilizers
    PEST_CONTROL,      // Spraying insecticides or biocontrol agents
    WEEDING,           // Manual or herbicide weeding
    HARVESTING,        // Gathering mature crops
    PRUNING,           // Trimming branches/foliage
    POST_HARVEST       // Cleaning, sorting, grading, drying
}
