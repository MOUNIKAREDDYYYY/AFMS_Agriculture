package com.AgricultureFMSystem.AgricultureFMSystem.repository;

import com.AgricultureFMSystem.AgricultureFMSystem.dto.response.HarvestSummaryDTO;
import com.AgricultureFMSystem.AgricultureFMSystem.entity.Harvest;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;
import org.springframework.stereotype.Repository;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.List;

/**
 * ============================================================================================
 * Phase 3: Spring Data JPA Repository - HarvestRepository (Harvest Records & Yield Aggregations)
 * ============================================================================================
 * Demonstrates:
 * - Aggregation Queries (SUM quantity, SUM totalRevenue, COUNT)
 * - Yield summaries grouped by Crop
 * - Date Range Filtering
 */
@Repository
public interface HarvestRepository extends JpaRepository<Harvest, Long> {

    Page<Harvest> findByFieldId(Long fieldId, Pageable pageable);

    Page<Harvest> findByCropId(Long cropId, Pageable pageable);

    // Date filtering: Harvests reaped between two dates
    @Query("SELECT h FROM Harvest h WHERE h.harvestDate BETWEEN :startDate AND :endDate ORDER BY h.harvestDate DESC")
    Page<Harvest> findByHarvestDateBetween(@Param("startDate") LocalDate startDate,
                                           @Param("endDate") LocalDate endDate,
                                           Pageable pageable);

    // Aggregation Query 1: Total harvest revenue generated by a farm
    @Query("SELECT COALESCE(SUM(h.totalRevenue), 0) FROM Harvest h WHERE h.field.farm.id = :farmId")
    BigDecimal sumHarvestRevenueByFarmId(@Param("farmId") Long farmId);

    // Aggregation Query 1b: Total harvest revenue generated across all farms
    @Query("SELECT COALESCE(SUM(h.totalRevenue), 0) FROM Harvest h")
    BigDecimal calculateTotalRevenueAcrossAllFarms();

    // Aggregation Query 2: Total harvest count for a farm
    @Query("SELECT COUNT(h) FROM Harvest h WHERE h.field.farm.id = :farmId")
    long countHarvestsByFarmId(@Param("farmId") Long farmId);

    // Aggregation Query 3: Harvest yield and revenue summary grouped by Crop
    @Query("SELECT new com.AgricultureFMSystem.AgricultureFMSystem.dto.response.HarvestSummaryDTO(" +
           "h.crop.id, h.crop.name, SUM(h.quantity), h.unit, SUM(h.totalRevenue), COUNT(h.id)) " +
           "FROM Harvest h " +
           "GROUP BY h.crop.id, h.crop.name, h.unit " +
           "ORDER BY SUM(h.totalRevenue) DESC")
    List<HarvestSummaryDTO> aggregateHarvestsByCrop();

    // Aggregation Query 4: Grouped by Crop with optional date filtering
    @Query("SELECT new com.AgricultureFMSystem.AgricultureFMSystem.dto.response.HarvestSummaryDTO(" +
           "h.crop.id, h.crop.name, SUM(h.quantity), h.unit, SUM(h.totalRevenue), COUNT(h.id)) " +
           "FROM Harvest h " +
           "WHERE (:startDate IS NULL OR h.harvestDate >= :startDate) " +
           "AND (:endDate IS NULL OR h.harvestDate <= :endDate) " +
           "GROUP BY h.crop.id, h.crop.name, h.unit " +
           "ORDER BY SUM(h.totalRevenue) DESC")
    List<HarvestSummaryDTO> aggregateHarvestsByCropAndDateRange(
            @Param("startDate") LocalDate startDate,
            @Param("endDate") LocalDate endDate);
}
